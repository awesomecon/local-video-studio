"""Score plan: timeline cues over the generated soundtrack, plus persistence.

ACE-Step composes the underlying music but does not honor exact timestamps.
Exact musical moves (pullbacks, silences, impacts) are therefore described by
a *score plan* that is applied afterward, deterministically, by FFmpeg:

    music/background.wav  +  music/score-plan.json  ->  music/scored-background.wav

``background.wav`` is never modified; it remains the original generated master.

The models here define the portable, human-readable ``score-plan.json``
schema (version 1), validate every cue, and read/write the plan atomically.
Rendering the automation into audio is a separate concern (the deterministic
``score_mix`` pipeline stage) that consumes exactly these models.
"""

